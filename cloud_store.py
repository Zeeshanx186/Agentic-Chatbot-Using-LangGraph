"""Neon persistence; local runs keep their existing SQLite/files when unset."""

from contextlib import contextmanager
from functools import lru_cache
import os
from pathlib import Path
import tempfile

from dotenv import load_dotenv

load_dotenv()
ENABLED = bool(os.environ.get("DATABASE_URL"))
DATA_ROOT = Path(tempfile.gettempdir()) / "dexter" if ENABLED else Path(__file__).parent


@lru_cache(maxsize=1)
def pool():
    from psycopg.rows import dict_row
    from psycopg_pool import ConnectionPool

    return ConnectionPool(
        os.environ["DATABASE_URL"], min_size=0, max_size=4,
        kwargs={"autocommit": True, "prepare_threshold": None, "row_factory": dict_row},
        timeout=30, check=ConnectionPool.check_connection, open=True,
    )


@lru_cache(maxsize=1)
def checkpoint():
    from langgraph.checkpoint.postgres import PostgresSaver

    return PostgresSaver(pool())


def setup_schema():
    """Run once before deployment, not concurrently during serverless cold starts."""
    checkpoint().setup()
    with pool().connection() as conn:
        conn.execute("""CREATE TABLE IF NOT EXISTS dexter_objects (
            key TEXT PRIMARY KEY, data BYTEA NOT NULL,
            metadata JSONB NOT NULL DEFAULT '{}'::jsonb)""")
        conn.execute("""CREATE TABLE IF NOT EXISTS dexter_metadata (
            namespace TEXT NOT NULL, key TEXT NOT NULL, value JSONB NOT NULL,
            PRIMARY KEY (namespace, key))""")
        conn.execute("""CREATE TABLE IF NOT EXISTS memories (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            fact TEXT NOT NULL, tag TEXT, created_at TEXT NOT NULL)""")


def memory_query(sql, params=()):
    from psycopg.rows import tuple_row

    with pool().connection() as conn, conn.cursor(row_factory=tuple_row) as cur:
        cur.execute(sql.replace("?", "%s"), params)
        return cur.fetchall() if cur.description else []


def get_object(key, conn=None):
    if conn is not None:
        return conn.execute("SELECT data, metadata FROM dexter_objects WHERE key=%s", (key,)).fetchone()
    with pool().connection() as conn:
        return get_object(key, conn)


def put_object(key, data, metadata=None, conn=None):
    from psycopg.types.json import Jsonb

    if conn is None:
        with pool().connection() as conn:
            return put_object(key, data, metadata, conn)
    conn.execute("""INSERT INTO dexter_objects VALUES (%s, %s, %s)
        ON CONFLICT (key) DO UPDATE SET data=EXCLUDED.data, metadata=EXCLUDED.metadata""",
        (key, data, Jsonb(metadata or {})))


def metadata_all(namespace):
    with pool().connection() as conn:
        rows = conn.execute("SELECT key, value FROM dexter_metadata WHERE namespace=%s", (namespace,))
        return {row["key"]: row["value"] for row in rows}


def metadata_set(namespace, key, value):
    from psycopg.types.json import Jsonb

    with pool().connection() as conn:
        if value is None:
            conn.execute("DELETE FROM dexter_metadata WHERE namespace=%s AND key=%s", (namespace, key))
        else:
            conn.execute("""INSERT INTO dexter_metadata VALUES (%s,%s,%s)
                ON CONFLICT (namespace,key) DO UPDATE SET value=EXCLUDED.value""",
                (namespace, key, Jsonb(value)))


def persist_path(path):
    if ENABLED:
        path = Path(path)
        key = path.resolve().relative_to(DATA_ROOT.resolve()).as_posix()
        put_object("file/" + key, path.read_bytes())


def restore_path(path):
    if not ENABLED or not path:
        return path
    target = Path(path)
    try:
        key = target.resolve().relative_to(DATA_ROOT.resolve()).as_posix()
    except ValueError:
        return path
    if not target.exists():
        stored = get_object("file/" + key)
        if stored:
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = target.with_name(target.name + "." + os.urandom(8).hex())
            temporary.write_bytes(bytes(stored["data"]))
            temporary.replace(target)
    return str(target)


@contextmanager
def rag_transaction():
    with pool().connection() as conn, conn.transaction():
        conn.execute("SELECT pg_advisory_xact_lock(73918421)")
        yield conn
